CREATE TABLE overtime_schedule (
    schedule_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id BIGINT GENERATED ALWAYS AS (schedule_id) STORED,
    title VARCHAR(150) NOT NULL,
    description TEXT,
    start_at TIMESTAMP NOT NULL,
    end_at TIMESTAMP NOT NULL,
    required_employees INTEGER NOT NULL DEFAULT 1,
    status VARCHAR(20) NOT NULL DEFAULT 'PUBLISHED',
    created_by BIGINT NOT NULL REFERENCES app_user(id) ON DELETE RESTRICT,
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_ot_time CHECK(end_at > start_at),
    CONSTRAINT chk_ot_status CHECK(status IN ('PUBLISHED', 'CANCELLED'))
);

CREATE TABLE overtime_registration (
    registration_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id BIGINT GENERATED ALWAYS AS (registration_id) STORED,
    schedule_id BIGINT NOT NULL REFERENCES overtime_schedule(schedule_id) ON DELETE RESTRICT,
    employee_id BIGINT NOT NULL REFERENCES employee(employee_id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    approved_by BIGINT REFERENCES app_user(id) ON DELETE SET NULL,
    decision_reason TEXT,
    decided_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_overtime_schedule_employee UNIQUE(schedule_id, employee_id),
    CONSTRAINT chk_ot_registration_status CHECK(status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED'))
);

CREATE TABLE approval_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    leave_request_id BIGINT REFERENCES leave_request(leave_request_id) ON DELETE CASCADE,
    actor_user_id BIGINT REFERENCES app_user(id) ON DELETE SET NULL,
    action VARCHAR(30) NOT NULL,
    reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_ot_schedule_start_at ON overtime_schedule(start_at);
CREATE INDEX idx_ot_registration_employee ON overtime_registration(employee_id, status);
