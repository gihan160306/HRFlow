CREATE TABLE department (
    department_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id BIGINT GENERATED ALWAYS AS (department_id) STORED,
    department_code VARCHAR(20) NOT NULL UNIQUE,
    department_name VARCHAR(100) NOT NULL UNIQUE,
    name VARCHAR(100) GENERATED ALWAYS AS (department_name) STORED,
    description VARCHAR(255),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE employee (
    employee_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id BIGINT GENERATED ALWAYS AS (employee_id) STORED,
    employee_code VARCHAR(20) NOT NULL UNIQUE,
    full_name VARCHAR(150) NOT NULL,
    work_email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(20),
    date_of_birth DATE,
    address VARCHAR(255),
    national_id VARCHAR(12) UNIQUE,
    tax_code VARCHAR(14),
    bank_name VARCHAR(100),
    bank_account_no VARCHAR(30),
    department_id BIGINT NOT NULL REFERENCES department(department_id) ON DELETE RESTRICT,
    job_title VARCHAR(100) NOT NULL,
    employee_type VARCHAR(10) NOT NULL DEFAULT 'STAFF',
    manager_id BIGINT REFERENCES employee(employee_id) ON DELETE SET NULL,
    hire_date DATE NOT NULL,
    status VARCHAR(12) NOT NULL DEFAULT 'ACTIVE',
    dependents_count SMALLINT NOT NULL DEFAULT 0,
    tax_commitment_08 BOOLEAN NOT NULL DEFAULT FALSE,
    ot_eligible BOOLEAN NOT NULL DEFAULT FALSE,
    commission_eligible BOOLEAN NOT NULL DEFAULT FALSE,
    kpi_eligible BOOLEAN NOT NULL DEFAULT FALSE,
    performance_bonus_eligible BOOLEAN NOT NULL DEFAULT FALSE,
    team_bonus_eligible BOOLEAN NOT NULL DEFAULT FALSE,
    lunch_allowance_eligible BOOLEAN NOT NULL DEFAULT FALSE,
    parking_allowance_eligible BOOLEAN NOT NULL DEFAULT FALSE,
    phone_allowance_eligible BOOLEAN NOT NULL DEFAULT FALSE,
    position_allowance_eligible BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_employee_type CHECK (employee_type IN ('STAFF', 'SALES', 'LEADER', 'MANAGER', 'INTERN')),
    CONSTRAINT chk_employee_status CHECK (status IN ('ACTIVE', 'TERMINATED')),
    CONSTRAINT chk_employee_not_self_manager CHECK (manager_id IS NULL OR manager_id <> employee_id)
);

CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT GENERATED ALWAYS AS (id) STORED,
    employee_id BIGINT UNIQUE REFERENCES employee(employee_id) ON DELETE SET NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'EMPLOYEE',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    active BOOLEAN GENERATED ALWAYS AS (is_active) STORED,
    last_login_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_app_user_role CHECK (role IN ('EMPLOYEE', 'MANAGER', 'HR', 'ADMIN'))
);

CREATE INDEX idx_employee_department_id ON employee(department_id);
CREATE INDEX idx_employee_manager_id ON employee(manager_id);
CREATE INDEX idx_employee_status ON employee(status);
CREATE INDEX idx_app_user_role ON app_user(role);
CREATE INDEX idx_app_user_email ON app_user(email);
