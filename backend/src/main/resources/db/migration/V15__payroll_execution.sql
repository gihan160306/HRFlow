CREATE OR REPLACE FUNCTION reject_final_payroll_edit() RETURNS trigger AS $$
DECLARE period_status TEXT;
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF TG_TABLE_NAME = 'payslip' THEN
            SELECT status INTO period_status FROM payroll_period WHERE id = NEW.payroll_period_id;
        ELSE
            SELECT pp.status INTO period_status FROM payroll_period pp
            JOIN payslip p ON p.payroll_period_id = pp.id WHERE p.payslip_id = NEW.payslip_id;
        END IF;
    ELSIF TG_TABLE_NAME = 'payslip' THEN
        SELECT status INTO period_status FROM payroll_period WHERE id = OLD.payroll_period_id;
    ELSE
        SELECT pp.status INTO period_status FROM payroll_period pp
        JOIN payslip p ON p.payroll_period_id = pp.id WHERE p.payslip_id = OLD.payslip_id;
    END IF;
    IF period_status IN ('APPROVED', 'LOCKED') THEN
        IF TG_TABLE_NAME = 'payslip' AND TG_OP = 'UPDATE' THEN
            IF OLD.status = 'CALCULATED' AND NEW.status = 'ISSUED'
                AND OLD.issued_at IS NULL AND NEW.issued_at IS NOT NULL
                AND to_jsonb(NEW) - 'status' - 'issued_at' - 'updated_at'
                    = to_jsonb(OLD) - 'status' - 'issued_at' - 'updated_at' THEN
                RETURN NEW;
            END IF;
        END IF;
        RAISE EXCEPTION 'Approved/locked payroll output is immutable' USING ERRCODE = '55006';
    END IF;
    IF TG_OP IN ('UPDATE', 'INSERT') THEN RETURN NEW; END IF;
    RETURN OLD;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_payslip_final_guard BEFORE INSERT OR UPDATE OR DELETE ON payslip
FOR EACH ROW EXECUTE FUNCTION reject_final_payroll_edit();
CREATE TRIGGER trg_payroll_line_final_guard BEFORE INSERT OR UPDATE OR DELETE ON payroll_line
FOR EACH ROW EXECUTE FUNCTION reject_final_payroll_edit();

CREATE OR REPLACE FUNCTION guard_payroll_state() RETURNS trigger AS $$
BEGIN
    IF NEW.status <> OLD.status AND NOT (
        (OLD.status = 'DRAFT' AND NEW.status = 'CALCULATED') OR
        (OLD.status = 'CALCULATED' AND NEW.status IN ('DRAFT', 'APPROVED')) OR
        (OLD.status = 'APPROVED' AND NEW.status = 'LOCKED')) THEN
        RAISE EXCEPTION 'Invalid payroll period transition' USING ERRCODE = '55006';
    END IF;
    IF OLD.status = 'LOCKED' THEN
        RAISE EXCEPTION 'Locked payroll period is immutable' USING ERRCODE = '55006';
    END IF;
    IF OLD.status = 'APPROVED' AND (
        NEW.status <> 'LOCKED' OR
        to_jsonb(NEW) - 'status' - 'locked_at' - 'updated_at'
            <> to_jsonb(OLD) - 'status' - 'locked_at' - 'updated_at') THEN
        RAISE EXCEPTION 'Approved payroll period is immutable' USING ERRCODE = '55006';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_payroll_period_state BEFORE UPDATE ON payroll_period
FOR EACH ROW EXECUTE FUNCTION guard_payroll_state();

