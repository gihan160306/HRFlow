CREATE TABLE department (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(20)  NOT NULL UNIQUE,
    name        VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(255),
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE TABLE job_title (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                 VARCHAR(30)  NOT NULL UNIQUE,
    name                 VARCHAR(100) NOT NULL,
    department_id        BIGINT REFERENCES department(id),
    managerial           BOOLEAN      NOT NULL DEFAULT FALSE,
    sales_owner_eligible BOOLEAN      NOT NULL DEFAULT FALSE,
    default_base_salary  NUMERIC(15,0),
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_job_title_department_id ON job_title(department_id);

CREATE TABLE employee (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code               VARCHAR(20)  NOT NULL UNIQUE,
    full_name          VARCHAR(150) NOT NULL,
    gender             VARCHAR(10),
    date_of_birth      DATE,
    phone              VARCHAR(20),
    personal_email     VARCHAR(255),
    work_email         VARCHAR(255) NOT NULL UNIQUE,
    address            VARCHAR(255),
    national_id        VARCHAR(20) UNIQUE,
    bank_name          VARCHAR(100),
    bank_account_no    VARCHAR(40),
    employee_type      VARCHAR(30)  NOT NULL,
    status             VARCHAR(30)  NOT NULL,
    hire_date          DATE         NOT NULL,
    termination_date   DATE,
    termination_reason VARCHAR(500),
    work_location      VARCHAR(255),
    wage_region        VARCHAR(30)  NOT NULL,
    department_id      BIGINT       NOT NULL REFERENCES department(id),
    job_title_id       BIGINT       NOT NULL REFERENCES job_title(id),
    manager_id         BIGINT REFERENCES employee(id),
    version            BIGINT       NOT NULL DEFAULT 0,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_employee_not_self_manager CHECK (manager_id IS NULL OR manager_id <> id),
    CONSTRAINT chk_employee_type CHECK (employee_type IN ('FULL_TIME', 'PART_TIME', 'PROBATION', 'INTERN')),
    CONSTRAINT chk_employee_status CHECK (status IN ('ONBOARDING', 'ACTIVE', 'ON_LEAVE', 'TERMINATED')),
    CONSTRAINT chk_employee_wage_region CHECK (wage_region IN ('REGION_I', 'REGION_II', 'REGION_III', 'REGION_IV'))
);
CREATE INDEX idx_employee_department_id ON employee(department_id);
CREATE INDEX idx_employee_job_title_id ON employee(job_title_id);
CREATE INDEX idx_employee_manager_id ON employee(manager_id);

