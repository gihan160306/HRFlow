CREATE TABLE audit_log (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_account_id BIGINT REFERENCES user_account(id),
    actor_name       VARCHAR(150),
    action           VARCHAR(80)  NOT NULL,
    entity_type      VARCHAR(50)  NOT NULL,
    entity_id        VARCHAR(50),
    result           VARCHAR(20)  NOT NULL,
    reason           VARCHAR(1000),
    before_json      JSONB,
    after_json       JSONB,
    ip_address       VARCHAR(60),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_audit_log_result CHECK (result IN ('SUCCESS', 'DENIED'))
);
CREATE INDEX idx_audit_created ON audit_log(created_at);
CREATE INDEX idx_audit_log_actor_account_id ON audit_log(actor_account_id);

CREATE TABLE background_job (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_type   VARCHAR(50)  NOT NULL,
    payload    JSONB,
    dedupe_key VARCHAR(200) UNIQUE,
    status     VARCHAR(30)  NOT NULL,
    attempts   INTEGER      NOT NULL DEFAULT 0,
    last_error VARCHAR(2000),
    run_after  TIMESTAMPTZ  NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_background_job_status CHECK (status IN ('PENDING', 'RUNNING', 'DONE', 'FAILED'))
);
CREATE INDEX idx_job_status ON background_job(status, run_after);

CREATE TABLE job_run_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_name    VARCHAR(100)  NOT NULL,
    run_key     VARCHAR(200),
    started_at  TIMESTAMPTZ   NOT NULL,
    finished_at TIMESTAMPTZ,
    result      VARCHAR(20)   NOT NULL,
    message     VARCHAR(2000)
);
