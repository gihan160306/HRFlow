CREATE TABLE system_parameter (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    param_key VARCHAR(100) NOT NULL,
    param_value VARCHAR(255) NOT NULL,
    value_type VARCHAR(20) NOT NULL DEFAULT 'STRING',
    description TEXT,
    effective_from DATE NOT NULL DEFAULT CURRENT_DATE,
    effective_to DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_system_parameter_effective UNIQUE(param_key, effective_from)
);

CREATE TABLE payroll_parameter (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parameter_key VARCHAR(100) NOT NULL,
    parameter_value VARCHAR(255) NOT NULL,
    value_type VARCHAR(20) NOT NULL DEFAULT 'STRING',
    description TEXT,
    effective_from DATE NOT NULL DEFAULT CURRENT_DATE,
    effective_to DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE tax_schedule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_code VARCHAR(30) NOT NULL UNIQUE,
    schedule_name VARCHAR(150) NOT NULL,
    effective_from DATE NOT NULL,
    effective_to DATE,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE tax_bracket (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tax_schedule_id BIGINT REFERENCES tax_schedule(id) ON DELETE CASCADE,
    tax_type VARCHAR(30) NOT NULL DEFAULT 'PIT_MONTHLY',
    lower_bound BIGINT NOT NULL,
    upper_bound BIGINT,
    tax_rate NUMERIC(7,6) NOT NULL,
    deduction_amount BIGINT NOT NULL DEFAULT 0,
    effective_from DATE NOT NULL DEFAULT CURRENT_DATE,
    effective_to DATE
);

CREATE TABLE calendar_exception (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calendar_date DATE NOT NULL UNIQUE,
    day_type VARCHAR(20) NOT NULL DEFAULT 'HOLIDAY',
    description VARCHAR(200) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE allowance_type (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    amount BIGINT NOT NULL DEFAULT 0,
    is_taxable BOOLEAN NOT NULL DEFAULT TRUE,
    is_insurable BOOLEAN NOT NULL DEFAULT FALSE,
    description TEXT
);

CREATE TABLE allowance_deduction_policy (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_code VARCHAR(40) NOT NULL UNIQUE,
    policy_name VARCHAR(150) NOT NULL,
    policy_type VARCHAR(20) NOT NULL,
    calculation_type VARCHAR(20) NOT NULL DEFAULT 'FIXED',
    amount BIGINT NOT NULL DEFAULT 0,
    rate NUMERIC(9,6),
    is_taxable BOOLEAN NOT NULL DEFAULT TRUE,
    is_insurable BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    effective_from DATE NOT NULL DEFAULT CURRENT_DATE,
    effective_to DATE,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE employee_policy_assignment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employee(employee_id) ON DELETE RESTRICT,
    policy_id BIGINT NOT NULL REFERENCES allowance_deduction_policy(id) ON DELETE RESTRICT,
    custom_amount BIGINT,
    effective_from DATE NOT NULL DEFAULT CURRENT_DATE,
    effective_to DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
