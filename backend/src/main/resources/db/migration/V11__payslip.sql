CREATE TABLE payslip (
    payslip_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id BIGINT GENERATED ALWAYS AS (payslip_id) STORED,
    payroll_period_id BIGINT NOT NULL REFERENCES payroll_period(id) ON DELETE RESTRICT,
    period_id BIGINT GENERATED ALWAYS AS (payroll_period_id) STORED,
    employee_id BIGINT NOT NULL REFERENCES employee(employee_id) ON DELETE RESTRICT,
    currency CHAR(3) NOT NULL DEFAULT 'VND',
    status VARCHAR(20) NOT NULL DEFAULT 'ISSUED',
    base_salary NUMERIC(15,0) NOT NULL DEFAULT 0,
    standard_working_days INTEGER NOT NULL DEFAULT 22,
    actual_worked_days NUMERIC(4,1) NOT NULL DEFAULT 22,
    paid_leave_days NUMERIC(4,1) NOT NULL DEFAULT 0,
    unpaid_leave_days NUMERIC(4,1) NOT NULL DEFAULT 0,
    gross_salary NUMERIC(15,0) NOT NULL DEFAULT 0,
    bhxh_amount NUMERIC(15,0) NOT NULL DEFAULT 0,
    bhyt_amount NUMERIC(15,0) NOT NULL DEFAULT 0,
    bhtn_amount NUMERIC(15,0) NOT NULL DEFAULT 0,
    total_employee_insurance NUMERIC(15,0) NOT NULL DEFAULT 0,
    personal_deduction NUMERIC(15,0) NOT NULL DEFAULT 11000000,
    taxable_income NUMERIC(15,0) NOT NULL DEFAULT 0,
    pit_amount NUMERIC(15,0) NOT NULL DEFAULT 0,
    other_deductions NUMERIC(15,0) NOT NULL DEFAULT 0,
    period_adjustments NUMERIC(15,0) NOT NULL DEFAULT 0,
    net_salary NUMERIC(15,0) NOT NULL DEFAULT 0,
    carried_debt NUMERIC(15,0) NOT NULL DEFAULT 0,
    pdf_path VARCHAR(500),
    pdf_generated_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_payslip_employee_period UNIQUE(employee_id, payroll_period_id)
);

CREATE TABLE payroll_line (
    payroll_line_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id BIGINT GENERATED ALWAYS AS (payroll_line_id) STORED,
    payslip_id BIGINT NOT NULL REFERENCES payslip(payslip_id) ON DELETE CASCADE,
    category VARCHAR(50) NOT NULL,
    label VARCHAR(255) NOT NULL,
    amount NUMERIC(15,0) NOT NULL DEFAULT 0,
    calculation_note TEXT,
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_payslip_period ON payslip(payroll_period_id);
CREATE INDEX idx_payslip_employee ON payslip(employee_id);
CREATE INDEX idx_payroll_line_payslip ON payroll_line(payslip_id);
