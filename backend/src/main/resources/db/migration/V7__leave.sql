CREATE TABLE leave_request (
    leave_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id BIGINT GENERATED ALWAYS AS (leave_request_id) STORED,
    employee_id BIGINT NOT NULL REFERENCES employee(employee_id) ON DELETE RESTRICT,
    leave_type VARCHAR(16) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    half_day_session VARCHAR(2),
    duration_days NUMERIC(4,1) NOT NULL,
    reason VARCHAR(500),
    status VARCHAR(10) NOT NULL DEFAULT 'DRAFT',
    submitted_at TIMESTAMPTZ,
    decided_by BIGINT REFERENCES app_user(id) ON DELETE SET NULL,
    decided_at TIMESTAMPTZ,
    decision_reason VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_leave_status CHECK(status IN ('DRAFT','PENDING','APPROVED','REJECTED','CANCELLED')),
    CONSTRAINT chk_leave_dates CHECK(end_date >= start_date)
);

CREATE TABLE leave_balance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employee(employee_id) ON DELETE RESTRICT,
    leave_year INTEGER NOT NULL,
    accrued_days NUMERIC(4,1) NOT NULL DEFAULT 12.0,
    used_days NUMERIC(4,1) NOT NULL DEFAULT 0.0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_leave_balance UNIQUE(employee_id, leave_year)
);

CREATE INDEX idx_leave_employee_dates ON leave_request(employee_id, start_date, end_date);
CREATE INDEX idx_leave_status ON leave_request(status);
