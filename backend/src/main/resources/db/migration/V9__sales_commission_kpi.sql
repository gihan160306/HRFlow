CREATE TABLE commission_rate (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employee(employee_id) ON DELETE RESTRICT,
    revenue_type VARCHAR(30) NOT NULL,
    rate NUMERIC(7,6) NOT NULL,
    effective_from DATE NOT NULL DEFAULT CURRENT_DATE,
    effective_to DATE
);

CREATE TABLE revenue_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employee(employee_id) ON DELETE RESTRICT,
    record_date DATE NOT NULL,
    client_name VARCHAR(200),
    campaign_name VARCHAR(200),
    reference_code VARCHAR(80) UNIQUE,
    revenue_amount BIGINT NOT NULL DEFAULT 0,
    eligible_commission_amount BIGINT NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    verified_by BIGINT REFERENCES app_user(id) ON DELETE SET NULL,
    verified_at TIMESTAMPTZ,
    note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE kpi_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employee(employee_id) ON DELETE RESTRICT,
    payroll_period_id BIGINT NOT NULL REFERENCES payroll_period(id) ON DELETE RESTRICT,
    kpi_code VARCHAR(50) NOT NULL,
    kpi_name VARCHAR(150) NOT NULL,
    target_value NUMERIC(14,4),
    actual_value NUMERIC(14,4),
    achievement_rate NUMERIC(9,6),
    score NUMERIC(9,4),
    bonus_amount BIGINT NOT NULL DEFAULT 0,
    evaluated_by BIGINT REFERENCES app_user(id) ON DELETE SET NULL,
    evaluated_at TIMESTAMPTZ,
    note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_kpi_employee_period_code UNIQUE(employee_id, payroll_period_id, kpi_code)
);

CREATE INDEX idx_revenue_employee_date ON revenue_record(employee_id, record_date);
CREATE INDEX idx_kpi_period_employee ON kpi_result(payroll_period_id, employee_id);
