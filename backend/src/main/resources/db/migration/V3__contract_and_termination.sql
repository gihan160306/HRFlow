CREATE TABLE contract (
    contract_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id BIGINT GENERATED ALWAYS AS (contract_id) STORED,
    employee_id BIGINT NOT NULL REFERENCES employee(employee_id) ON DELETE RESTRICT,
    contract_no VARCHAR(50) NOT NULL UNIQUE,
    contract_type VARCHAR(12) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE,
    base_salary NUMERIC(15,0),
    monthly_stipend NUMERIC(15,0),
    probation_rate NUMERIC(4,3),
    insurance_salary NUMERIC(15,0),
    probation_insured BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(14) NOT NULL DEFAULT 'ACTIVE',
    renewed_from_contract_id BIGINT REFERENCES contract(contract_id) ON DELETE SET NULL,
    note VARCHAR(500),
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_contract_type CHECK (contract_type IN ('PROBATION', 'FIXED_TERM', 'INDEFINITE', 'INTERNSHIP')),
    CONSTRAINT chk_contract_status CHECK (status IN ('ACTIVE', 'EXPIRING_SOON', 'EXPIRED', 'TERMINATED')),
    CONSTRAINT chk_contract_dates CHECK (end_date IS NULL OR end_date >= start_date)
);

CREATE TABLE termination_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employee(employee_id) ON DELETE RESTRICT,
    notice_date DATE NOT NULL,
    termination_date DATE NOT NULL,
    reason TEXT,
    created_by BIGINT REFERENCES app_user(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_contract_employee_id ON contract(employee_id);
CREATE INDEX idx_contract_status_end_date ON contract(status, end_date);
