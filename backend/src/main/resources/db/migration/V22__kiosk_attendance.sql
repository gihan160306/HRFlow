-- V22: Cham cong tai quay (SRS 3.4 - DEC-10, database_design.md 3.6)
-- Nhan vien hien thi QR ca nhan dong tren dien thoai; may cham cong tai quay (tai khoan thiet bi KIOSK)
-- quet ma, chup anh minh chung roi ghi cong. Bo QR cua diem cham cong do HR cap (qr_token, ma ngan).

-- 1. Tai khoan thiet bi KIOSK: khong gan nhan vien, bat buoc gan mot diem cham cong.
--    KIOSK la loai tai khoan thiet bi, khong phai role nen tang cua nguoi dung (SRS Muc 2.4).
ALTER TABLE user_account DROP CONSTRAINT chk_user_account_role;
ALTER TABLE user_account ADD CONSTRAINT chk_user_account_role
    CHECK (role IN ('EMPLOYEE', 'MANAGER', 'HR', 'ADMIN', 'KIOSK'));
ALTER TABLE user_account ADD COLUMN attendance_point_id BIGINT REFERENCES attendance_point(id);
ALTER TABLE user_account ADD CONSTRAINT chk_user_account_kiosk
    CHECK ((role = 'KIOSK') = (employee_id IS NULL AND attendance_point_id IS NOT NULL));
CREATE INDEX idx_user_account_attendance_point_id ON user_account(attendance_point_id);

-- 2. Anh minh chung luon bat buoc cho check-in va check-out.
ALTER TABLE attendance_point DROP COLUMN photo_required;

-- 3. QR ca nhan dong cua nhan vien, kiem phien quet tai quay.
CREATE TABLE employee_qr_token (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id    BIGINT      NOT NULL REFERENCES employee(id),
    nonce          VARCHAR(64) NOT NULL,
    issued_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at     TIMESTAMPTZ NOT NULL,
    revoked_at     TIMESTAMPTZ,
    scanned_at     TIMESTAMPTZ,
    scanned_by     BIGINT REFERENCES user_account(id),
    punch_type     VARCHAR(20),
    punch_deadline TIMESTAMPTZ,
    used_at        TIMESTAMPTZ,
    attendance_id  BIGINT REFERENCES attendance_record(id),
    CONSTRAINT employee_qr_token_nonce_key UNIQUE (nonce),
    CONSTRAINT chk_eqr_punch_type CHECK (punch_type IS NULL OR punch_type IN ('CHECK_IN', 'CHECK_OUT')),
    CONSTRAINT chk_eqr_scan CHECK ((scanned_at IS NULL) = (scanned_by IS NULL)),
    CONSTRAINT chk_eqr_used CHECK (used_at IS NULL OR scanned_at IS NOT NULL)
);
CREATE INDEX idx_eqr_employee_active ON employee_qr_token(employee_id) WHERE used_at IS NULL AND revoked_at IS NULL;
CREATE INDEX idx_eqr_scanned_by ON employee_qr_token(scanned_by);
CREATE INDEX idx_eqr_expires_at ON employee_qr_token(expires_at);

DROP TABLE qr_token;

-- 4. Ban ghi cong va anh luu may quay da ghi/chup.
ALTER TABLE attendance_record ADD COLUMN check_in_kiosk_id BIGINT REFERENCES user_account(id);
ALTER TABLE attendance_record ADD COLUMN check_out_kiosk_id BIGINT REFERENCES user_account(id);
CREATE INDEX idx_attendance_record_check_in_kiosk_id ON attendance_record(check_in_kiosk_id);
CREATE INDEX idx_attendance_record_check_out_kiosk_id ON attendance_record(check_out_kiosk_id);

ALTER TABLE attendance_photo ADD COLUMN captured_by BIGINT REFERENCES user_account(id);
CREATE INDEX idx_attendance_photo_captured_by ON attendance_photo(captured_by);

