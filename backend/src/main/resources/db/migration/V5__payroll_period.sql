CREATE TABLE payroll_period (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payroll_period_id BIGINT GENERATED ALWAYS AS (id) STORED,
    period_id BIGINT GENERATED ALWAYS AS (id) STORED,
    period_code VARCHAR(20) NOT NULL UNIQUE,
    period_name VARCHAR(100) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    payment_date DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    standard_working_days INTEGER NOT NULL DEFAULT 22,
    created_by BIGINT REFERENCES app_user(id) ON DELETE SET NULL,
    approved_by BIGINT REFERENCES app_user(id) ON DELETE SET NULL,
    approved_at TIMESTAMPTZ,
    locked_at TIMESTAMPTZ,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_payroll_dates CHECK(end_date >= start_date),
    CONSTRAINT chk_payroll_status CHECK(status IN ('DRAFT','CALCULATED','APPROVED','LOCKED'))
);

CREATE INDEX idx_payroll_period_dates ON payroll_period(start_date, end_date);
CREATE INDEX idx_payroll_period_status ON payroll_period(status);
