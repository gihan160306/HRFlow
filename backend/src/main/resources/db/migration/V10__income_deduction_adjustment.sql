CREATE TABLE payroll_adjustment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employee(employee_id) ON DELETE RESTRICT,
    payroll_period_id BIGINT NOT NULL REFERENCES payroll_period(id) ON DELETE RESTRICT,
    direction VARCHAR(15) NOT NULL,
    category VARCHAR(30) NOT NULL,
    description VARCHAR(255) NOT NULL,
    amount BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    source_reference VARCHAR(100),
    reason TEXT,
    created_by BIGINT REFERENCES app_user(id) ON DELETE SET NULL,
    approved_by BIGINT REFERENCES app_user(id) ON DELETE SET NULL,
    approved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_adjustment_employee_period ON payroll_adjustment(employee_id, payroll_period_id);
