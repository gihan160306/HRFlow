CREATE TABLE attendance (
    attendance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id BIGINT GENERATED ALWAYS AS (attendance_id) STORED,
    employee_id BIGINT NOT NULL REFERENCES employee(employee_id) ON DELETE RESTRICT,
    work_date DATE NOT NULL,
    check_in_at TIMESTAMPTZ,
    check_out_at TIMESTAMPTZ,
    late_minutes INTEGER NOT NULL DEFAULT 0,
    early_minutes INTEGER NOT NULL DEFAULT 0,
    worked_minutes INTEGER NOT NULL DEFAULT 0,
    day_credit NUMERIC(2,1) NOT NULL DEFAULT 0.0,
    status VARCHAR(10) NOT NULL DEFAULT 'OPEN',
    source VARCHAR(20) NOT NULL DEFAULT 'WEB',
    exception_decision VARCHAR(12),
    decided_by BIGINT REFERENCES app_user(id) ON DELETE SET NULL,
    decided_at TIMESTAMPTZ,
    decision_reason VARCHAR(500),
    confirmed_by BIGINT REFERENCES app_user(id) ON DELETE SET NULL,
    note VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_attendance_employee_date UNIQUE(employee_id, work_date),
    CONSTRAINT chk_attendance_status CHECK(status IN ('OPEN','PRESENT','EXCEPTION','ABSENT','LEAVE','REMOTE')),
    CONSTRAINT chk_attendance_source CHECK(source IN ('WEB','QR','MANAGER_CONFIRMED','HR_CORRECTION'))
);

CREATE INDEX idx_attendance_work_date ON attendance(work_date);
CREATE INDEX idx_attendance_employee_date ON attendance(employee_id, work_date);
